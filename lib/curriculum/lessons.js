export function stageForLevel(level) {
  return STAGES.find((stage) => stage.levels.includes(level));
}

export function getLesson(slug) {
  return LESSONS.find((lesson) => lesson.slug === slug) || null;
}

export function lessonsForLevel(level) {
  return LESSONS.filter((lesson) => lesson.level === level);
}

export function isProLesson(lesson) {
  const stage = stageForLevel(lesson.level);
  return Boolean(stage?.requiresPro);
}
